def detect_language(env: Optional[Mapping[str, str]] = None) -> str:
    """按 ``LC_ALL`` → ``LANG`` 选择 CLI 语言，未匹配时用英文。"""
    source = env if env is not None else os.environ
    raw = (source.get("LC_ALL") or source.get("LANG") or "").strip()
    if not raw:
        return DEFAULT
    code = raw.split(".")[0].split("@")[0].replace("_", "-").lower()
    if code in ("c", "posix"):
        return DEFAULT
    primary = code.split("-")[0]
    return primary if primary in SUPPORTED else DEFAULT


def translate(lang: str, key: str, **kwargs: object) -> str:
    """取文案；缺键时回退英文，再回退键名。"""
    text = MESSAGES.get(lang, MESSAGES[DEFAULT]).get(key)
    if text is None:
        text = MESSAGES[DEFAULT].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text


def make_translator(lang: str):
    def _t(key: str, **kwargs: object) -> str:
        return translate(lang, key, **kwargs)

    return _t
